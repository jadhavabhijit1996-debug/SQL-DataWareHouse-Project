--CREATING SALES FACT VIEW
--=====================================================================
Select * from silver.crm_sales_details;
--we will be connecting fact table to dimensions table using surrogate key from dimensions table
--here sls_prd_key and sls_cust_id will be taken using surrogate key(product_key, customer_key) from gold dimensions view of customers and products
Select
	sd.sls_ord_num,
	pr.product_key,
	cm.customer_key,
	sd.sls_order_dt,
	sd.sls_ship_dt,
	sd.sls_due_dt,
	sd.sls_sales,
	sd.sls_quantity,
	sd.sls_price
from silver.crm_sales_details AS sd
LEFT JOIN gold.dim_customers as cm
ON sd.sls_cust_id = cm.customer_id
LEFT JOIN gold.dim_products AS pr
ON sd.sls_prd_key = pr.product_number

--renaming the columns and ordering in logical groups
Select
	sd.sls_ord_num AS order_number,
	pr.product_key,
	cm.customer_key,
	sd.sls_order_dt AS order_date,
	sd.sls_ship_dt AS shipping_date,
	sd.sls_due_dt AS due_date,
	sd.sls_sales AS sales_amount,
	sd.sls_quantity AS sales_quantity,
	sd.sls_price AS price
from silver.crm_sales_details AS sd
LEFT JOIN gold.dim_customers as cm
ON sd.sls_cust_id = cm.customer_id
LEFT JOIN gold.dim_products AS pr
ON sd.sls_prd_key = pr.product_number

--CREATING FACT_SALES VIEW
--=============================================================

IF OBJECT_ID('gold.fact_sales','V') IS NOT NULL
	DROP gold.fact_sales;
GO

CREATE VIEW gold.fact_sales AS
Select
	sd.sls_ord_num AS order_number,
	pr.product_key,
	cm.customer_key,
	sd.sls_order_dt AS order_date,
	sd.sls_ship_dt AS shipping_date,
	sd.sls_due_dt AS due_date,
	sd.sls_sales AS sales_amount,
	sd.sls_quantity AS sales_quantity,
	sd.sls_price AS price
from silver.crm_sales_details AS sd
LEFT JOIN gold.dim_customers as cm
ON sd.sls_cust_id = cm.customer_id
LEFT JOIN gold.dim_products AS pr
ON sd.sls_prd_key = pr.product_number
